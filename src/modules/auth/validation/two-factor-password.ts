import { z } from "zod";

/**
 * Пароль второго фактора при вводе (verify/disable): от 6 символов — так
 * задавались существующие пароли 2FA, более строгий минимум заблокировал бы их.
 */
export const twoFactorPassword = z
  .string()
  .min(6, "Пароль 2FA должен содержать минимум 6 символов")
  .max(100, "Пароль 2FA не должен превышать 100 символов");

/** Текущий пароль аккаунта — подтверждение чувствительного действия. */
export const currentPassword = z
  .string()
  .min(1, "Укажите текущий пароль")
  .max(100, "Пароль не должен превышать 100 символов");

/**
 * Новый пароль 2FA (enable): от 8 символов, как и пароль аккаунта. Список
 * частых паролей не применяется — это второй фактор за основным паролем
 * с собственной блокировкой (5 неудач / 15 мин).
 */
export const newTwoFactorPassword = z
  .string()
  .min(8, "Пароль 2FA должен содержать минимум 8 символов")
  .max(100, "Пароль 2FA не должен превышать 100 символов");
